package com.langfundamentals;

public class Method100 {
	void firstName(String Fname) {
		System.out.println("First name is:" + Fname);
	}

	void middleName(String Mname) {
		System.out.println("Middle name is:" + Mname);
	}

	void lastName(String lname) {
		System.out.println("Last name is:" + lname);
	}

	void homeName(String hname) {
		System.out.println("Home name is:" + hname);
	}

	void fatherName(String fname) {
		System.out.println("Father name is:" + fname);
	}

	void gender(char c) {
		System.out.println("gender is:" + c);
	}

	void main() {
		firstName("siddu");
		middleName("sai");
		lastName("triveni");
		homeName("Sreeyapureddy");
		fatherName("Surya narayana Reddy");
		gender('f');
	}

}

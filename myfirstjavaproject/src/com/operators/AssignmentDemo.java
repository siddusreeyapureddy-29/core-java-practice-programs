package com.operators;

public class AssignmentDemo {
// Assignment operators =,+=,-=,*=,/=,%=
	public static void main(String[] args) {
		int result=0;
		result=result+4;
//		System.out.println(result);
//		result=(int)(result+4.5);
//		System.out.println(result);
		result+=4.5;
		System.out.println(result);
		result-=2.5;
		System.out.println(result);
		result*=9.5;
		System.out.println(result);
		result/=4;
		System.out.println(result);
		result%=4;
		System.out.println(result);
		

	}

}
